"""키워드 문자열 정규화 공용부 — 소스 간 병합과 자기 질의어 제외가 같은 규칙을 쓰게 한다.

두 도구를 제공하고, 쓰는 쪽이 무엇을 쓸지 **명시적으로** 고른다:

- `squeezed` — 공백을 전부 지운다. **전체 일치** 비교에만 쓴다("개발자 연봉"과
  "개발자연봉"은 같은 말). 소스 간 후보 병합·자기 질의어 제외가 이 경우다.
- `collapsed` — 공백 런을 하나로 줄이기만 한다(지우지 않는다). **부분 문자열** 검사에 쓴다.
  공백을 지우고 부분 검사를 하면 인접 단어의 끝·앞 글자가 붙어 없던 말이 생긴다
  ("최고 장점" → "최고장점" ⊃ "고장"). 제외 키워드 판정이 이 경우다.

둘을 섞어 쓰면 조용히 오탐이 난다. 그래서 한 파일에 나란히 두고 차이를 docstring에 박는다.
"""

import re

_WHITESPACE = re.compile(r"\s+")


def squeezed(text: str) -> str:
    """대소문자 무시 + 공백 전부 제거. 두 문자열이 같은 말인지 볼 때만."""
    return _WHITESPACE.sub("", text).casefold()


def collapsed(text: str) -> str:
    """대소문자 무시 + 공백 런을 단일 공백으로 축약 + 양끝 공백 제거.

    공백을 **제거하지 않는 것**이 핵심이다 — 제거하면 단어 경계가 사라져 오탐이 생긴다.
    """
    return _WHITESPACE.sub(" ", text).strip().casefold()
